const express=require('express');
const {requireAuth,requireArea,requireRole}=require('../middleware/auth');
const ctrl=require('../controllers/workspace.controller');
const router=express.Router();
router.get('/lead-duplicates',requireAuth,requireArea('leads'),ctrl.duplicates);
router.get('/search',requireAuth,ctrl.search);
router.get('/access',requireAuth,requireRole('admin'),ctrl.access);
const payments=require('../controllers/workspacePayments.controller');
router.get('/renewals/:id/payments',requireAuth,requireArea('renewals'),payments.list);
router.post('/renewals/:id/payments',requireAuth,requireArea('renewals'),payments.create);
router.post('/payments/:id/void',requireAuth,requireRole('admin'),payments.voidPayment);
const preferences=require('../controllers/workspacePreferences.controller');
router.get('/notification-preferences',requireAuth,preferences.get);
router.put('/notification-preferences',requireAuth,preferences.put);
router.post('/link-check',requireAuth,requireArea('content'),require('express-rate-limit')({windowMs:60000,max:3,standardHeaders:true,legacyHeaders:false}),require('../controllers/workspaceLinks.controller').audit);
const restore=require('../controllers/workspaceRestore.controller');
router.get('/restore-status',requireAuth,requireRole('admin'),restore.status);
router.post('/backups/:name/restore-drill',requireAuth,requireRole('admin'),restore.start);
module.exports=router;
